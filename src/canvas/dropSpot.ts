/**
 * **고르면 바로 놓인다 — 그 「어디에」를 정하는 곳.**
 *
 * 2026-09-17 · 사용자 제보: 「현재는 슬라이드를 클릭해야 도형이 뜨는데?」
 * 도형 갤러리에서 모양을 골라도 화면에는 아무 일도 안 일어났다. 팝업만 닫히고
 * 커서가 십자로 바뀔 뿐이라, **한 번 더 눌러야 한다는 걸 모르는 사람에게는
 * 고장으로 보인다.**
 *
 * 이건 이미 한 번 내린 결론이다. `FreeLayer` 의 '삽입 → 이미지' 자리에 이렇게 적혀 있다:
 *   「도구만 켜두면 "캔버스를 한 번 더 클릭해야 한다"는 걸 모르는 사람이
 *     아무 반응 없다고 느낀다.」
 * 그래서 그림·이모지·아이콘은 벌써 곧바로 놓인다. **도형만 빠져 있었다.**
 *
 * 막을 까닭도 없었다. 도형 만들기는 끌어서 크기를 정하는 방식이 아니라
 * 정해진 크기로 놓고 자리만 클릭 지점이다(`mkFreeEl`). 그 두 번째 클릭이 하는 일은
 * 「어디에」뿐이고, 놓인 뒤엔 어차피 끌어서 옮긴다.
 *
 * ── 왜 한가운데 + 비껴 놓기인가 (사용자 결정 ㄴ) ──────────────────
 * 한가운데 **고정**이면 연달아 둘을 놓았을 때 정확히 포개져서, 두 번째를 놓고도
 * 「안 생겼나?」 싶다 — 고치려던 증상이 모양만 바꿔 되돌아온다.
 * 「빈 곳을 찾아서 자동으로」는 똑똑해 보이지만 **왜 저기 놓였는지 설명이 안 되는**
 * 자리가 나온다. 그래서 한가운데에서 시작해, 그 자리가 이미 차 있으면 16px 씩 비껴 놓는다.
 * 16 은 복제(⌘D)가 쓰는 값과 같다 — 손에 이미 익은 움직임이다.
 *
 * **겹침이 아니라 「똑같이 포개짐」만 피한다.** 표준 양식이 종이를 거의 다 덮고 있어서
 * 진짜 겹침을 피하려 들면 밀다가 종이 밖으로 나간다. 도형이 요소 위에 그려지는 건
 * 2026-09-17 에 고쳐 둔 대로 잘못이 아니다.
 */
export const CASCADE = 16
/** 비껴 놓기를 몇 번까지 해 볼지. 넘어가면 그냥 한가운데에 겹쳐 놓는다. */
export const MAX_STEPS = 12

export interface Spot { x: number; y: number }
export interface Box { x: number; y: number; w: number; h: number }

/**
 * **「이미 차 있다」는 왼쪽 위가 아니라 가운데로 잰다.**
 *
 * 처음에는 왼쪽 위 모서리끼리 비교했다. 실제로 놓아 보니 그게 틀렸다:
 * 네모는 120×56, 동그라미는 96×96 — **갈래마다 기본 크기가 다르다.** 둘 다 한가운데에
 * 놓으면 모서리는 12px, 20px 씩 어긋나 「안 겹쳤다」고 판정되는데, **가운데는 정확히
 * 같아서 작은 쪽이 큰 쪽을 완전히 덮는다.** 피하려던 바로 그 일이 일어난다.
 * (시험 서버 실측: 네모 @460,332 · 동그라미 @472,312 — 중심은 둘 다 520,360)
 */
export function centerSpot(taken: readonly Box[], w: number, h: number, W: number, H: number): Spot {
  const x0 = Math.max(0, Math.round(W / 2 - w / 2))
  const y0 = Math.max(0, Math.round(H / 2 - h / 2))
  for (let i = 0; i < MAX_STEPS; i++) {
    const x = x0 + i * CASCADE, y = y0 + i * CASCADE
    // **종이 밖으로는 안 민다.** 밖에 놓인 요소는 아무에게도 안 보이고,
    // 작성자는 결재에 올린 뒤에야 안다(`penIn` 의 주석과 같은 까닭).
    if (x + w > W || y + h > H) break
    const cx = x + w / 2, cy = y + h / 2
    if (!taken.some((t) => Math.abs(t.x + t.w / 2 - cx) < CASCADE && Math.abs(t.y + t.h / 2 - cy) < CASCADE)) return { x, y }
  }
  return { x: x0, y: y0 }
}
