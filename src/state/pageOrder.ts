/**
 * **새 슬라이드가 들어갈 자리.**
 *
 * 2026-09-18 · 전에는 늘 맨 끝에 붙었다. 재 보니 3장짜리에서 가운데(2번째)를 골라 놓고
 * 「＋ 슬라이드」를 눌러도 **4번째**로 갔다 — 만들고 나서 손으로 끌어 올려야 했다.
 * 파워포인트·키노트는 고른 것 바로 뒤에 넣는다(사용자 결정).
 *
 * **셈을 밖으로 꺼내 둔 까닭**은 시험 때문이다. 스토어 안에 두면 가드가 같은 셈을
 * **복사해서** 재게 되는데, 그러면 복사본이 맞는지를 재는 꼴이라 정작 스토어가 달라져도
 * 모른다(같은 덫을 이 저장소에서 이미 한 번 밟았다 — 간격을 자기 상수로 재던 가드).
 */
export function slideSpot(pages: readonly { id: number }[], selectedId: number | null): number {
  const at = pages.findIndex((p) => p.id === selectedId)
  // **고른 쪽이 없으면 맨 끝.** -1 을 그냥 쓰면 0 번 자리에 박혀 맨 앞에 끼어든다.
  return at < 0 ? pages.length : at + 1
}
